import type { Mod, SpeciesId, TechCategory } from '../types';

export interface TechDef {
  id: string;
  name: string;
  category: TechCategory;
  era: 1 | 2 | 3 | 4;
  cost: number;
  prereqs: string[];
  effects: Mod[];
  species?: SpeciesId; // only this species can research it
  text: string;
}

const ERA_COST = { 1: 40, 2: 110, 3: 200, 4: 350 } as const;

function t(
  id: string,
  name: string,
  category: TechCategory,
  era: 1 | 2 | 3 | 4,
  prereqs: string[],
  effects: Mod[],
  text: string,
  species?: SpeciesId,
): TechDef {
  return { id, name, category, era, cost: ERA_COST[era], prereqs, effects, text, species };
}

