import type { ResourceId, SpeciesId } from '../types';

export type UnitClass = 'military' | 'civilian';

export interface UnitDef {
  id: string;
  name: string;
  cls: UnitClass;
  cost: number;
  strength: number; // defence strength, and attack strength for melee units
  ranged?: number; // ranged attack strength
  range?: number;
  ground?: number; // ground strength for invasion
  move: number;
  sight: number;
  tech?: string;
  resource?: ResourceId;
  replaces?: string; // base unit that this species unit replaces
  species?: SpeciesId;
  upgradesTo?: string;
  canColonize?: boolean;
  colonyPop?: number; // population of a new colony, 1 when not set
  colonyBuilding?: string; // building that a new colony starts with
  canBuild?: boolean; // builds stations
  buildSpeed?: number; // turns removed from station build time
  vsPlanet?: number; // strength bonus share against planets
  defenceBonus?: number; // strength bonus share when it defends
  homeBonus?: number; // strength bonus share inside own borders
  bounty?: number; // share of the killed unit cost paid in credits
  contactBonus?: number; // attitude added at first contact
  voidborn?: boolean; // enters Void Rifts without a drive and moves between rifts
  text: string;
}

